// Token Radar's model: the sealed snapshot in, one ranked board out.
//
// The board ranks every protocol that records no token and is not a wrapped,
// staked or bridged product of a token that already trades. The snapshot's
// watchlist is the floor: all 40 of its slugs are ranked, and the board adds
// every other rankable protocol below the floor, so the radar covers the
// whole pre-token universe the snapshot holds, not just its biggest names.
//
// Implied value is a claim built only from the snapshot's own figures:
//
//   comparable multiple = the median market-cap-to-TVL ratio of the
//     launched protocols in the same category (at least 3 of them), or the
//     median across the launched protocols outside the wrapped categories
//     when a category is too thin; the multiple is clamped to 0.02–2.50.
//   base       = tvl_usd x comparable multiple
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x 0.5
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4
//   implied    = max(1, round(base x growthMult x maturity))
//
// Age is the days since the protocol was first listed: how long it has run
// with no token on record. An unknown listing date uses 365 days. No
// protocol name is ever special-cased: the same function scores every row,
// and the dashboard prints each row's breakdown so a reader can check it.

/** One protocol as the sealed snapshot carries it: exactly ten fields. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, printed on the dashboard. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  multiple_floor: number;
  multiple_cap: number;
  min_comparables: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
  multiple_floor: 0.02,
  multiple_cap: 2.5,
  min_comparables: 3,
};

